import { Pool, type QueryResult, type QueryResultRow } from "pg";
import { hashPassword } from "./passwords.js";

type SqlValue = string | number | boolean | null;

export interface QueryExecutor {
  query<Row extends QueryResultRow = QueryResultRow>(
    text: string,
    values?: readonly SqlValue[],
  ): Promise<QueryResult<Row>>;
}

const connectionString = process.env.DATABASE_URL;

if (!connectionString) {
  throw new Error("DATABASE_URL is required to connect to the PostgreSQL database.");
}

const pool = new Pool({
  connectionString,
  ssl: process.env.NODE_ENV === "production" ? { rejectUnauthorized: false } : undefined,
});

export function query<Row extends QueryResultRow = QueryResultRow>(
  text: string,
  values: readonly SqlValue[] = [],
): Promise<QueryResult<Row>> {
  return pool.query<Row>(text, [...values]);
}

export async function inTransaction<Result>(
  operation: (executor: QueryExecutor) => Promise<Result>,
): Promise<Result> {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const executor: QueryExecutor = {
      query: <Row extends QueryResultRow = QueryResultRow>(
        text: string,
        values: readonly SqlValue[] = [],
      ) => client.query<Row>(text, [...values]),
    };
    const result = await operation(executor);
    await client.query("COMMIT");
    return result;
  } catch (error) {
    try {
      await client.query("ROLLBACK");
    } catch (rollbackError) {
      throw new AggregateError(
        [error, rollbackError],
        "Database transaction failed and could not be rolled back.",
      );
    }
    throw error;
  } finally {
    client.release();
  }
}

export async function initializeDatabase(): Promise<void> {
  await query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      is_admin BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TEXT NOT NULL
    );
    CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_idx ON users (LOWER(username));

    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at BIGINT NOT NULL,
      created_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON sessions(expires_at);

    CREATE TABLE IF NOT EXISTS rooms (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'drawn')),
      created_by INTEGER NOT NULL REFERENCES users(id),
      created_at TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS room_members (
      room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      joined_at TEXT NOT NULL,
      PRIMARY KEY (room_id, user_id)
    );

    CREATE TABLE IF NOT EXISTS wishlists (
      room_id INTEGER NOT NULL,
      user_id INTEGER NOT NULL,
      text TEXT NOT NULL DEFAULT '',
      updated_at TEXT NOT NULL,
      PRIMARY KEY (room_id, user_id),
      FOREIGN KEY (room_id, user_id)
        REFERENCES room_members(room_id, user_id) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS assignments (
      room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
      giver_id INTEGER NOT NULL,
      recipient_id INTEGER NOT NULL,
      created_at TEXT NOT NULL,
      PRIMARY KEY (room_id, giver_id),
      UNIQUE (room_id, recipient_id),
      CHECK (giver_id <> recipient_id),
      FOREIGN KEY (room_id, giver_id)
        REFERENCES room_members(room_id, user_id) ON DELETE CASCADE,
      FOREIGN KEY (room_id, recipient_id)
        REFERENCES room_members(room_id, user_id) ON DELETE CASCADE
    );
  `);

  await query("DELETE FROM sessions WHERE expires_at <= $1", [Date.now()]);

  const adminResult = await query("SELECT id FROM users WHERE is_admin = TRUE LIMIT 1");
  if (adminResult.rowCount) return;

  const adminUsername =
    process.env.ADMIN_USERNAME ??
    (process.env.NODE_ENV === "production" ? undefined : "admin");
  const adminPassword =
    process.env.ADMIN_PASSWORD ??
    (process.env.NODE_ENV === "production" ? undefined : "admin");

  if (!adminUsername || !adminPassword) {
    throw new Error(
      "ADMIN_USERNAME and ADMIN_PASSWORD are required to create the initial admin account.",
    );
  }

  await query(
    "INSERT INTO users (username, password_hash, is_admin, created_at) VALUES ($1, $2, TRUE, $3)",
    [adminUsername, hashPassword(adminPassword), new Date().toISOString()],
  );
}

export async function closeDatabase(): Promise<void> {
  await pool.end();
}
